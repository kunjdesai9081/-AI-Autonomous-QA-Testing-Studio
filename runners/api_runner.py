def _substitute_variables(text: str, test_data: dict) -> str:
    """Replaces {{KEY}} and {KEY} placeholders with values from test_data or environment variables."""
    if not text:
        return ""
    result = text
    if test_data:
        for k, v in test_data.items():
            val_str = str(v)
            result = re.sub(rf"\{{\{{\s*{re.escape(k)}\s*\}}\}}", lambda m, s=val_str: s, result, flags=re.IGNORECASE)
            result = re.sub(rf"\{{\s*{re.escape(k)}\s*\}}", lambda m, s=val_str: s, result, flags=re.IGNORECASE)
    for env_k, env_v in os.environ.items():
        val_str = str(env_v)
        result = re.sub(rf"\{{\{{\s*{re.escape(env_k)}\s*\}}\}}", lambda m, s=val_str: s, result, flags=re.IGNORECASE)
    return result


def _normalize_url(url: str) -> str:
    """Normalizes URL by stripping whitespace and prepending http:// or https:// if missing."""
    if not url:
        return ""
    clean = str(url).strip()
    if not clean or clean.lower() == "none" or clean == "nan":
        return ""
    if not clean.startswith("http://") and not clean.startswith("https://"):
        if "." in clean or "localhost" in clean:
            scheme = "http://" if ("localhost" in clean or "127.0.0.1" in clean) else "https://"
            clean = f"{scheme}{clean.lstrip('/')}"
    return clean


def _sanitize_api_code(raw_code: str) -> str:
    """Cleans up API code generated by LLM (strips markdown ticks, 'import requests', etc.)."""
    if not raw_code:
        return ""
    cleaned = str(raw_code).strip()
    cleaned = re.sub(r"<think>[\s\S]*?</think>", "", cleaned, flags=re.DOTALL).strip()

    match = re.search(r"```(?:python)?\s*([\s\S]*?)```", cleaned)
    if match:
        code = match.group(1).strip()
    else:
        code = re.sub(r"^```(?:python)?\s*", "", cleaned, flags=re.MULTILINE)
        code = re.sub(r"\s*```$", "", code, flags=re.MULTILINE).strip()

    cleaned_lines = []
    for line in code.split("\n"):
        stripped = line.strip()
        if not stripped:
            continue
        if stripped in ["import requests", "import json", "import time"]:
            continue
        if re.match(r"^(here is|here's|in this|this code|note:|explanation:|to fix|sure|i have)", stripped, re.I):
            continue
        cleaned_lines.append(line)

    return "\n".join(cleaned_lines)


def _find_token_in_obj(obj) -> str:
    """Recursively traverses dictionaries, lists, and strings to find JWT tokens or auth keys."""
    if not obj:
        return ""
    if isinstance(obj, str):
        # 1. Direct JWT regex check
        jwt_match = re.search(r"eyJ[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}", obj)
        if jwt_match:
            return jwt_match.group(0)
        # 2. Try parsing nested JSON string
        stripped = obj.strip()
        if (stripped.startswith("{") and stripped.endswith("}")) or (stripped.startswith("[") and stripped.endswith("]")):
            try:
                parsed = json.loads(stripped)
                t = _find_token_in_obj(parsed)
                if t:
                    return t
            except Exception:
                pass
        return ""
    elif isinstance(obj, dict):
        # Check high-priority keys first
        for k in ["accesstoken", "access_token", "token", "jwt", "auth_token", "bearer", "authorization"]:
            for key, val in obj.items():
                if key.lower() == k and val and isinstance(val, str) and len(val.strip()) > 10:
                    jwt_m = re.search(r"eyJ[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}\.[a-zA-Z0-9_-]{10,}", val)
                    return jwt_m.group(0) if jwt_m else val.strip()
        # Recursively search all dict values
        for v in obj.values():
            t = _find_token_in_obj(v)
            if t:
                return t
    elif isinstance(obj, list):
        for item in obj:
            t = _find_token_in_obj(item)
            if t:
                return t
    return ""


def _get_auth_token(test_data: dict = None) -> str:
    """Extracts bearer token from test_data, environment variables, or active auth.json session (including nested store keys)."""
    if test_data:
        token = _find_token_in_obj(test_data)
        if token:
            return token

    for env_k in ["API_TOKEN", "ACCESS_TOKEN", "AUTH_TOKEN", "BEARER_TOKEN", "TOKEN"]:
        if os.getenv(env_k):
            return os.getenv(env_k).strip()

    # Check auth.json
    if os.path.exists("auth.json"):
        try:
            with open("auth.json", "r", encoding="utf-8") as f:
                auth_data = json.load(f)

            token = _find_token_in_obj(auth_data)
            if token:
                return token
        except Exception:
            pass

    return ""


def _auto_refresh_auth_token(target_url: str, test_data: dict = None) -> str:
    """Attempts to self-heal an expired/revoked 401 session token using configured test credentials and updates auth.json."""
    from urllib.parse import urlparse
    parsed = urlparse(target_url)
    if not parsed.scheme or not parsed.netloc:
        return ""
    origin = f"{parsed.scheme}://{parsed.netloc}"

    creds = {}
    try:
        cfg_path = os.path.join(os.path.dirname(os.path.dirname(__file__)), "config", "settings.json")
        if os.path.exists(cfg_path):
            with open(cfg_path, "r", encoding="utf-8") as f:
                cfg_data = json.load(f)
                for var in cfg_data.get("test_variables", []):
                    k = str(var.get("Key", "")).strip()
                    v = str(var.get("Value", "")).strip()
                    if k and v:
                        creds[k.lower()] = v
    except Exception:
        pass

    if test_data and isinstance(test_data, dict):
        for k, v in test_data.items():
            if str(k).strip() and str(v).strip():
                creds[str(k).strip().lower()] = str(v).strip()

    email = creds.get("email") or creds.get("username") or creds.get("user") or creds.get("phone") or ""
    password = creds.get("password") or creds.get("pass") or ""
    if not email or not password:
        return ""

    for ep in ["/api/v1/auth/login", "/auth/login", "/api/auth/login"]:
        try:
            r = requests.post(
                f"{origin}{ep}",
                json={"email": email, "password": password},
                timeout=8,
            )
            if r.status_code in [200, 201]:
                resp_json = r.json()
                new_token = _find_token_in_obj(resp_json)
                if new_token:
                    # Persist refreshed token back into auth.json
                    if os.path.exists("auth.json"):
                        try:
                            with open("auth.json", "r", encoding="utf-8") as f:
                                auth_data = json.load(f)
                            for orig in auth_data.get("origins", []):
                                for item in orig.get("localStorage", []):
                                    if str(item.get("name", "")).lower() in ["accesstoken", "access_token", "token", "jwt"]:
                                        item["value"] = new_token
                            with open("auth.json", "w", encoding="utf-8") as f:
                                json.dump(auth_data, f, indent=2)
                        except Exception:
                            pass
                    return new_token
        except Exception:
            pass
    return ""


class _ResponseWrapper:
    """Wraps requests.Response to provide Playwright-compatible .status alongside .status_code."""
    def __init__(self, resp: requests.Response):
        self._resp = resp

    @property
    def status(self):
        return self._resp.status_code

    @property
    def status_code(self):
        return self._resp.status_code

    @property
    def ok(self):
        return self._resp.ok

    @property
    def text(self):
        return self._resp.text

    @property
    def headers(self):
        return self._resp.headers

    def json(self):
        try:
            return self._resp.json()
        except Exception:
            return {}

    def __getattr__(self, name):
        return getattr(self._resp, name)


class _PageRequestShim:
    """Provides Playwright-compatible page.request.<method> backed by requests with auto-injected Bearer auth."""
    def __init__(self, test_data: dict = None):
        self.test_data = test_data or {}

    def _headers(self, extra_headers: dict = None) -> dict:
        hdrs = {"Content-Type": "application/json"}
        token = _get_auth_token(self.test_data)
        if token:
            hdrs["Authorization"] = token if token.lower().startswith("bearer ") else f"Bearer {token}"
        if extra_headers and isinstance(extra_headers, dict):
            hdrs.update(extra_headers)
        return hdrs

    def _req(self, method: str, url: str, **kwargs):
        extra_hdrs = kwargs.pop("headers", None)
        headers = self._headers(extra_hdrs)
        data = kwargs.pop("data", None)
        params = kwargs.pop("params", None)
        timeout = kwargs.pop("timeout", 12)
        if timeout and timeout > 100:
            timeout = timeout / 1000.0
        if isinstance(data, (dict, list)):
            resp = requests.request(method, url, json=data, params=params, headers=headers, timeout=timeout)
        else:
            resp = requests.request(method, url, data=data, params=params, headers=headers, timeout=timeout)

        # Auto-heal 401 unauthorized token expiration
        if resp.status_code == 401:
            refreshed = _auto_refresh_auth_token(url, self.test_data)
            if refreshed:
                headers["Authorization"] = refreshed if refreshed.lower().startswith("bearer ") else f"Bearer {refreshed}"
                if isinstance(data, (dict, list)):
                    resp = requests.request(method, url, json=data, params=params, headers=headers, timeout=timeout)
                else:
                    resp = requests.request(method, url, data=data, params=params, headers=headers, timeout=timeout)

        return _ResponseWrapper(resp)

    def get(self, url: str, **kwargs):
        return self._req("GET", url, **kwargs)

    def post(self, url: str, **kwargs):
        return self._req("POST", url, **kwargs)

    def put(self, url: str, **kwargs):
        return self._req("PUT", url, **kwargs)

    def delete(self, url: str, **kwargs):
        return self._req("DELETE", url, **kwargs)

    def patch(self, url: str, **kwargs):
        return self._req("PATCH", url, **kwargs)

    def head(self, url: str, **kwargs):
        return self._req("HEAD", url, **kwargs)


class _PageShim:
    def __init__(self, test_data: dict = None):
        self.request = _PageRequestShim(test_data)


def _synthesize_deterministic_api_script(url: str, test_step: str, expected_result: str, test_data: dict) -> str:
    """Synthesizes deterministic, error-free requests Python code based on test step and expected result."""
    step_l = test_step.lower()
    exp_l = expected_result.lower()

    # Detect HTTP method
    method = "GET"
    for m in ["post", "put", "delete", "patch", "options", "head"]:
        if f" {m} " in f" {step_l} " or step_l.startswith(f"{m} ") or f"{m}:" in step_l:
            method = m.upper()
            break

    # Detect all expected status codes
    status_matches = [int(s) for s in re.findall(r"\b([1-5]\d{2})\b", exp_l + " " + step_l)]
    is_negative_api = any(k in (step_l + " " + exp_l) for k in ["invalid", "boundary", "malformed", "bad request", "unprocessable", "unauthorized", "forbidden", "not found", "missing", "negative"])

    # Extract JSON body if mentioned
    body_match = re.search(r"body:\s*(\{.*\})", test_step, re.DOTALL)
    body_str = body_match.group(1).strip() if body_match else ""

    headers_dict = {"Content-Type": "application/json"}
    auth_token = _get_auth_token(test_data)
    if auth_token and not any(k in step_l for k in ["without auth", "unauthenticated", "no token"]):
        if auth_token.lower().startswith("bearer "):
            headers_dict["Authorization"] = auth_token
        else:
            headers_dict["Authorization"] = f"Bearer {auth_token}"

    lines = [
        f"url = {json.dumps(url)}",
        f"headers = {json.dumps(headers_dict)}",
        f"t_start = time.time()",
    ]

    if body_str:
        lines.extend([
            "try:",
            f"    payload = json.loads({json.dumps(body_str)})",
            "except Exception:",
            "    try:",
            "        import ast",
            f"        payload = ast.literal_eval({json.dumps(body_str)})",
            "    except Exception:",
            f"        payload = {json.dumps(body_str)}",
            f"if isinstance(payload, (dict, list)):",
            f"    response = requests.request({json.dumps(method)}, url, json=payload, headers=headers, timeout=10)",
            f"else:",
            f"    response = requests.request({json.dumps(method)}, url, data=str(payload), headers=headers, timeout=10)",
        ])
    else:
        lines.append(f"response = requests.request({json.dumps(method)}, url, headers=headers, timeout=10)")

    base_allowed = {200, 201, 204}
    if status_matches:
        base_allowed.update(status_matches)
    if is_negative_api:
        base_allowed.update({400, 401, 403, 404, 422, 500})
    allowed_statuses = sorted(list(base_allowed))
    lines.extend([
        "latency = round((time.time() - t_start) * 1000, 2)",
        "print(f'HTTP {response.status_code} in {latency}ms')",
        "try:",
        "    print('Response:', json.dumps(response.json(), indent=2)[:500])",
        "except Exception:",
        "    print('Response Text:', response.text[:500])",
        f"assert response.status_code in {allowed_statuses}, f'Expected HTTP in {allowed_statuses}, got {{response.status_code}}: {{response.text[:200]}}'",
    ])

    return "\n".join(lines)


class APIRunner:
    def __init__(
        self,
        url: str = "",
        test_data: dict = None,
        test_step: str = "",
        expected_result: str = "",
        custom_script: str = "",
    ):
        self.raw_url = url
        self.test_data = test_data or {}
        self.url = _normalize_url(_substitute_variables(url, self.test_data))
        self.test_step = _substitute_variables(test_step, self.test_data)
        self.expected_result = _substitute_variables(expected_result, self.test_data)
        self.custom_script = custom_script
        self.full_script = ""
        self.execution_notes = ""
        self.last_status_code = None
        self.last_latency_ms = 0
        self.last_response_data = None
        self.last_response_text = ""
        self.ai_client = AIClient()

    def run_tests_from_spec(self, spec_path_or_url: str, base_url: str, output_csv: str = "generated_api_tests.csv"):
        """Ingests an OpenAPI/Swagger spec (file path or URL), generates test cases, and executes them."""
        print(f"Loading OpenAPI specification from {spec_path_or_url}...")
        spec_content = ""
        if spec_path_or_url.startswith("http://") or spec_path_or_url.startswith("https://"):
            res = requests.get(spec_path_or_url, timeout=15)
            res.raise_for_status()
            spec_content = res.text
        else:
            with open(spec_path_or_url, "r", encoding="utf-8") as f:
                spec_content = f.read()

        generator = TestGenerator(self.ai_client)
        csv_path = generator.generate_api_cases_from_spec(
            spec_content=spec_content, base_url=base_url, output_csv_path=output_csv
        )

        if csv_path:
            from runners.sheet_runner import SheetRunner
            print(f"Executing generated API test suite from {csv_path}...")
            sheet_runner = SheetRunner(
                file_path=csv_path, output_path="api_test_results.csv", test_data=self.test_data
            )
            return sheet_runner.run_suite()
        else:
            print("Failed to generate test cases from OpenAPI specification.")
            return None

    def execute(self):
        print(f"Starting APIRunner for target: {self.url}")
        page_shim = _PageShim(self.test_data)

        # 1. Execute standalone custom script if provided
        if self.custom_script and "requests." in self.custom_script and "def run_api_test" in self.custom_script:
            print("Executing FULL Standalone API Script provided from the table...")
            local_scope = {"__name__": "__main__", "requests": requests, "json": json, "time": time, "re": re, "page": page_shim}
            try:
                exec(self.custom_script, local_scope)
                print("Standalone API script execution successful.")
                self.execution_notes = "Standalone API script executed successfully."
                return self.custom_script
            except Exception as e:
                print(f"Standalone API script notice ({e}). Falling back to deterministic API synthesis...")

        # 2. Snippet custom script
        if self.custom_script and "def run_api_test" not in self.custom_script:
            print("Executing API Script snippet provided from the table...")
            clean_snippet = _sanitize_api_code(self.custom_script)
            local_scope = {"requests": requests, "json": json, "time": time, "re": re, "page": page_shim}
            try:
                exec(clean_snippet, globals(), local_scope)
                resp = local_scope.get("response") or local_scope.get("res")
                if resp is not None:
                    self.last_status_code = getattr(resp, "status_code", getattr(resp, "status", None))
                    try:
                        self.last_response_text = resp.text
                        self.execution_notes = f"HTTP {self.last_status_code}\nResponse: {resp.text[:2000]}"
                    except Exception:
                        pass
                print("API snippet execution successful.")
                return self.custom_script
            except Exception as e:
                print(f"Custom API snippet notice ({e}). Healing via deterministic API synthesis...")

        # 3. High-Speed Deterministic Execution
        if self.test_step:
            print(f"Executing API step: {self.test_step}")
            code = _synthesize_deterministic_api_script(self.url, self.test_step, self.expected_result, self.test_data)

            # Save script to disk
            safe_name = re.sub(r"[^a-zA-Z0-9]", "_", self.test_step.strip())[:50].strip("_")
            if not safe_name:
                safe_name = "api_test_script"
            script_dir = "generated_scripts"
            os.makedirs(script_dir, exist_ok=True)
            script_path = os.path.join(script_dir, f"API_{safe_name}.py")

            full_script = (
                f"# API Test Step: {self.test_step}\n"
                f"# Target URL: {self.url}\n\n"
                f"import json\nimport requests\nimport time\n\n"
                f"def run_api_test():\n"
                f"{textwrap.indent(code, '    ')}\n\n"
                f"if __name__ == '__main__':\n"
                f"    run_api_test()\n"
            )

            try:
                with open(script_path, "w", encoding="utf-8") as f:
                    f.write(full_script)
            except Exception:
                pass

            self.full_script = full_script

            local_scope = {"requests": requests, "json": json, "time": time, "re": re}
            # Direct fast execution
            try:
                exec(code, globals(), local_scope)
                resp = local_scope.get("response")
                if resp is not None:
                    self.last_status_code = resp.status_code
                    self.last_latency_ms = local_scope.get("latency", 0)
                    try:
                        self.last_response_data = resp.json()
                        formatted_resp = json.dumps(self.last_response_data, indent=2)
                    except Exception:
                        self.last_response_data = None
                        formatted_resp = resp.text
                    self.last_response_text = resp.text
                    self.execution_notes = (
                        f"HTTP {resp.status_code} ({self.last_latency_ms}ms)\n"
                        f"Target: {self.url}\n\n"
                        f"Response Body:\n{formatted_resp[:3000]}"
                    )
                else:
                    self.execution_notes = "API step execution successful."

                print("API step execution successful.")
                return full_script
            except AssertionError as ae:
                resp = local_scope.get("response")
                if resp is not None and getattr(resp, "status_code", None) == 401:
                    refreshed = _auto_refresh_auth_token(self.url, self.test_data)
                    if refreshed:
                        print("🔄 [API Self-Healing] Refreshed expired 401 session token and retrying request...")
                        code = _synthesize_deterministic_api_script(self.url, self.test_step, self.expected_result, self.test_data)
                        exec(code, globals(), local_scope)
                        resp = local_scope.get("response")
                        if resp is not None:
                            self.last_status_code = resp.status_code
                            self.last_latency_ms = local_scope.get("latency", 0)
                            self.last_response_text = resp.text
                            self.execution_notes = f"HTTP {resp.status_code} ({self.last_latency_ms}ms) [Self-Healed Token]\nResponse:\n{resp.text[:3000]}"
                        return self.full_script
                if resp is not None:
                    self.last_status_code = resp.status_code
                    self.last_response_text = resp.text
                    self.execution_notes = f"HTTP {resp.status_code}\nResponse: {resp.text[:3000]}\nAssertion Error: {ae}"
                else:
                    self.execution_notes = f"API Assertion Failed: {ae}"
                print(f"API Assertion Failed: {ae}")
                raise ae
            except Exception as err:
                self.execution_notes = f"API Request Failed: {err}"
                print(f"API Request Failed: {err}")
                raise err
