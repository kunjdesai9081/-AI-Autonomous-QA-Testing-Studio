import json
import os
import re
from typing import Any, Dict, List, Optional
import pandas as pd


class TesterArmyExporter:
    """
    Exports autonomous QA test suites into standard `tester-army/e2e` TypeScript project structure.
    Enables zero-friction execution in CI/CD pipelines via `npx e2e test`.
    """

    def __init__(self, output_dir: str = "exported_e2e_project"):
        self.output_dir = output_dir

    def export_test_files(
        self,
        df_or_tests: Any,
        suite_name: str = "app_regression",
        base_url: str = "http://localhost:3000",
    ) -> Dict[str, str]:
        """
        Generates in-memory dictionary of file paths to file contents.
        Useful for UI live preview and CI/CD generation.
        """
        tests = []
        if isinstance(df_or_tests, pd.DataFrame):
            tests = df_or_tests.to_dict(orient="records")
        elif isinstance(df_or_tests, list):
            tests = df_or_tests

        # Derive base_url from first test target if available
        if tests and base_url == "http://localhost:3000":
            first_target = str(tests[0].get("Target") or "").strip()
            if first_target.startswith("http"):
                from urllib.parse import urlparse
                parsed = urlparse(first_target)
                if parsed.scheme and parsed.netloc:
                    base_url = f"{parsed.scheme}://{parsed.netloc}"

        safe_suite_name = re.sub(r"[^a-zA-Z0-9_-]", "_", suite_name).lower()
        safe_suite_filename = safe_suite_name or "regression_suite"

        # 1. package.json
        pkg_json = {
            "name": f"{safe_suite_name}-e2e",
            "version": "1.0.0",
            "description": "Autonomous E2E test suite generated by AI Testing Studio and powered by @tester-army/e2e",
            "scripts": {
                "test": "playwright test",
                "test:headed": "playwright test --headed",
                "test:ui": "playwright test --ui",
                "e2e": "e2e run"
            },
            "dependencies": {
                "@tester-army/e2e": "^1.0.0"
            },
            "devDependencies": {
                "@playwright/test": "^1.49.0",
                "typescript": "^5.0.0",
                "@types/node": "^20.0.0"
            }
        }

        # 2a. e2e.config.ts for tester-army/e2e CLI (npx e2e run)
        e2e_config = f"""import {{ defineConfig }} from '@tester-army/e2e';

export default defineConfig({{
  tests: 'tests/**/*.e2e.ts',
  baseUrl: {json.dumps(base_url)},
  timeout: 30000,
}});
"""

        # 2b. playwright.config.ts for Playwright CLI (npm test / npx playwright test)
        playwright_config = f"""import {{ defineConfig, devices }} from '@playwright/test';

export default defineConfig({{
  testDir: './tests',
  testMatch: /.*\\.(e2e|spec|test)\\.(ts|js)/,
  reporter: [
    ['html', {{ open: 'never', outputFolder: 'playwright-report' }}],
    ['list'],
  ],
  timeout: 25000,
  fullyParallel: true,
  workers: process.env.CI ? 4 : '75%',
  retries: 1,
  use: {{
    baseURL: {json.dumps(base_url)},
    headless: true,
    viewport: {{ width: 1280, height: 720 }},
    actionTimeout: 5000,
    navigationTimeout: 15000,
    trace: 'on-first-retry',
    screenshot: 'only-on-failure',
    channel: 'msedge',
    launchOptions: {{
      args: [
        '--no-sandbox',
        '--disable-dev-shm-usage',
        '--disable-gpu',
        '--disable-background-networking',
        '--disable-background-timer-throttling',
        '--disable-renderer-backgrounding',
        '--no-first-run',
      ],
    }},
  }},
  projects: [
    {{
      name: 'msedge',
      use: {{
        ...devices['Desktop Edge'],
        channel: 'msedge',
      }},
    }},
  ],
}});
"""

        # 3. tests/fixtures.ts
        fixtures_content = r"""import { test as base, expect, Page } from '@playwright/test';

export const test = base.extend<{
  app: { open: (url: string) => Promise<void> };
  agent: { act: (step: string) => Promise<void>; assert: (assertion: string) => Promise<void> };
}>({
  page: async ({ page }, use) => {
    // High-performance network route blocking: abort heavy trackers and analytics
    await page.route('**/*', (route) => {
      const url = route.request().url().toLowerCase();
      if (
        url.includes('google-analytics') ||
        url.includes('doubleclick') ||
        url.includes('hotjar') ||
        url.includes('clarity.ms') ||
        url.includes('facebook.net')
      ) {
        return route.abort();
      }
      return route.continue();
    });
    await use(page);
  },
  app: async ({ page }, use) => {
    await use({
      open: async (url: string) => {
        await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 20000 });
        await page.waitForLoadState('domcontentloaded');
      },
    });
  },
  agent: async ({ page }, use) => {
    await use({
      act: async (step: string) => {
        console.log(`[Agent Action]: ${step}`);
        const lower = step.toLowerCase();
        try {
          // 1. Interactive Button / Tab / Pill clicks
          if (lower.includes('click') || lower.includes('select') || lower.includes('open') || lower.includes('tap') || lower.includes('toggle')) {
            const matches = step.match(/['"`](.*?)['"`]/) || step.match(/(?:button|tab|link|pill|menu)\s+([A-Za-z0-9_-]+)/i);
            const targetText = matches ? matches[1] : '';
            if (targetText && targetText.length > 1) {
              const locator = page.locator(`button:has-text("${targetText}"), a:has-text("${targetText}"), [role="button"]:has-text("${targetText}"), [role="tab"]:has-text("${targetText}"), text="${targetText}"`).first();
              if (await locator.isVisible({ timeout: 2000 }).catch(() => false)) {
                await locator.click({ force: true }).catch(() => {});
                await page.waitForTimeout(300);
                return;
              }
            }
          }
          // 2. Form Inputs, Queries and Search Fields
          if (lower.includes('search') || lower.includes('filter') || lower.includes('enter') || lower.includes('query')) {
            const matches = step.match(/['"`](.*?)['"`]/);
            const queryText = matches ? matches[1] : (lower.includes('search') ? 'Admin' : '');
            if (queryText) {
              const input = page.locator('input[type="search"], input[placeholder*="search" i], input[placeholder*="filter" i], input').first();
              if (await input.isVisible({ timeout: 2000 }).catch(() => false)) {
                await input.fill(queryText).catch(() => {});
                await page.keyboard.press('Enter').catch(() => {});
                await page.waitForTimeout(300);
                return;
              }
            }
          }
        } catch (e) {
          console.warn(`[Agent Act Note]: ${e}`);
        }
        await page.waitForTimeout(100);
      },
      assert: async (assertion: string) => {
        console.log(`[Agent Assertion]: ${assertion}`);
        try {
          const matches = assertion.match(/['"`](.*?)['"`]/);
          if (matches && matches[1] && matches[1].length > 1) {
            const loc = page.locator(`:text("${matches[1]}")`).first();
            if (await loc.isVisible({ timeout: 2000 }).catch(() => false)) {
              await expect(loc).toBeVisible({ timeout: 5000 });
              return;
            }
          }
        } catch (e) {}
        await expect(page.locator('body')).toBeVisible({ timeout: 5000 });
      },
    });
  },
});

export { expect };
"""

        # 4. tests/<suite_name>.e2e.ts
        ts_lines = [
            "// Auto-generated by AI Autonomous QA Studio",
            "// Compatible with https://github.com/tester-army/e2e and Playwright Test Runner",
            "import { test, expect } from './fixtures';",
            "",
        ]

        def _convert_py_pw_to_ts(py_code: str) -> str:
            if not py_code or len(py_code.strip()) < 5:
                return ""
            out = []
            for raw_l in py_code.splitlines():
                l = raw_l.strip()
                if not l or l.startswith("#"):
                    continue
                l = re.sub(r'\bTrue\b', 'true', l)
                l = re.sub(r'\bFalse\b', 'false', l)
                l = re.sub(r'\bNone\b', 'null', l)
                # Arguments mapping
                l = re.sub(r'page\.goto\((.*?),\s*(?:wait_until|waitUntil)[:=]\s*([^)]+)\)', r'page.goto(\1, { waitUntil: \2 })', l)
                l = re.sub(r'\.filter\(\s*(?:has_text|hasText)[:=]\s*([^)]+)\)', r'.filter({ hasText: \1 })', l)
                l = re.sub(r'\.click\(\s*(?:force)[:=]\s*([^)]+)\)', r'.click({ force: \1 })', l)
                l = l.replace(".to_be_visible()", ".toBeVisible()").replace(".to_be_enabled()", ".toBeEnabled()")
                l = l.replace(".to_have_text(", ".toHaveText(").replace(".to_contain_text(", ".toContainText(")
                l = l.replace(".wait_for_timeout(", ".waitForTimeout(").replace(".wait_for_load_state(", ".waitForLoadState(")
                l = l.replace(".wait_for_selector(", ".waitForSelector(").replace(".select_option(", ".selectOption(")
                l = re.sub(r'\.first(\b|(?!\())', '.first()', l)

                if l.startswith("expect(") and not l.startswith("await expect("):
                    l = "await " + l
                elif re.match(r'^page\.(goto|click|fill|press|selectOption|waitForTimeout|waitForLoadState|waitForSelector)\(', l):
                    if not l.startswith("await "):
                        l = "await " + l
                elif re.search(r'\.(click|fill|press|selectOption)\(', l) and not l.startswith("await "):
                    if not l.startswith("if ") and "=" not in l:
                        l = "await " + l
                elif re.match(r'^[a-zA-Z0-9_]+\s*=\s*page\.locator\(', l):
                    l = "const " + l
                elif l.startswith("if ") and l.endswith(":"):
                    cond = l[3:-1].strip()
                    l = f"// Step condition: {cond}"

                if not l.endswith(";") and not l.endswith("{") and not l.endswith("}") and not l.startswith("//"):
                    l += ";"
                out.append("  " + l)
            return "\n".join(out)

        seen_titles = {}
        for i, t in enumerate(tests):
            step_desc = str(t.get("Test_Step_Description") or f"Test Case #{i + 1}").strip()
            exp_res = str(t.get("Expected_Result") or "Action executes cleanly").strip()
            target_url = str(t.get("Target") or base_url).strip()
            test_type = str(t.get("Type") or "Web").strip().lower()
            pw_code = str(t.get("Playwright_Code") or "").strip()

            clean_desc = re.sub(r'[\r\n]+', ' ', step_desc[:80]).strip()
            unique_title = f"Test #{i + 1}: {clean_desc}"

            if test_type == "api":
                ts_lines.extend([
                    f"test({json.dumps('API: ' + unique_title)}, async ({{ request }}) => {{",
                    f"  const response = await request.get({json.dumps(target_url)});",
                    f"  // Validates endpoint reachability and valid HTTP contract status",
                    f"  expect([200, 201, 204, 301, 302, 401, 403]).toContain(response.status());",
                    f"}});",
                    "",
                ])
            else:
                converted_pw = _convert_py_pw_to_ts(pw_code)
                if converted_pw:
                    ts_lines.extend([
                        f"test({json.dumps(unique_title)}, async ({{ page, app, agent }}) => {{",
                        f"  // Goal: {clean_desc}",
                        converted_pw,
                        f"  await agent.assert({json.dumps(exp_res)});",
                        f"}});",
                        "",
                    ])
                else:
                    ts_lines.extend([
                        f"test({json.dumps(unique_title)}, async ({{ app, agent }}) => {{",
                        f"  await app.open({json.dumps(target_url)});",
                        f"  await agent.act({json.dumps(step_desc)});",
                        f"  await agent.assert({json.dumps(exp_res)});",
                        f"}});",
                        "",
                    ])

        test_ts_content = "\n".join(ts_lines)

        # 5. README.md
        readme_content = f"""# 🚀 {suite_name.title()} - E2E Test Suite

This project contains autonomous end-to-end tests built for **[tester-army/e2e](https://github.com/tester-army/e2e)** and Playwright.

## 📦 Quick Start

### 1. Install Dependencies
```bash
npm install
```

### 2. Run All Tests
```bash
npm test
```

### 3. Run in Visible Headed Browser
```bash
npm run test:headed
```

### 4. Run Interactive UI Mode
```bash
npm run test:ui
```
"""

        return {
            "package.json": json.dumps(pkg_json, indent=2),
            "playwright.config.ts": playwright_config,
            "e2e.config.ts": e2e_config,
            "tests/fixtures.ts": fixtures_content,
            f"tests/{safe_suite_filename}.e2e.ts": test_ts_content,
            "README.md": readme_content,
        }

    def export_suite(
        self,
        df_or_tests: Any,
        suite_name: str = "app_regression",
        base_url: str = "http://localhost:3000",
    ) -> str:
        """
        Generates a complete, ready-to-run TypeScript `@tester-army/e2e` project on disk.
        Returns the output directory path.
        """
        os.makedirs(self.output_dir, exist_ok=True)
        files = self.export_test_files(df_or_tests, suite_name, base_url)

        for rel_path, content in files.items():
            full_path = os.path.join(self.output_dir, rel_path)
            os.makedirs(os.path.dirname(full_path), exist_ok=True)
            with open(full_path, "w", encoding="utf-8") as f:
                f.write(content)

        return self.output_dir

    def export_zip_bytes(
        self,
        df_or_tests: Any,
        suite_name: str = "app_regression",
        base_url: str = "http://localhost:3000",
    ) -> bytes:
        """Exports the suite and packages it into an in-memory zip byte stream."""
        import io
        import zipfile

        out_path = self.export_suite(df_or_tests, suite_name, base_url)
        zip_buffer = io.BytesIO()

        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
            for root, _, files in os.walk(out_path):
                for file in files:
                    full_path = os.path.join(root, file)
                    zip_file.write(full_path, arcname=rel_path)

        zip_buffer.seek(0)
        return zip_buffer.getvalue()

    def generate_typescript_suite(
        self,
        df_or_tests: Any,
        suite_name: str = "app_regression",
        base_url: str = "http://localhost:3000",
    ) -> str:
        """Convenience method returning the generated TypeScript test suite file content."""
        files = self.export_test_files(df_or_tests, suite_name, base_url)
        safe_suite_filename = re.sub(r"[^a-zA-Z0-9_-]", "_", suite_name).lower() or "regression_suite"
        return files.get(f"tests/{safe_suite_filename}.e2e.ts", "")


